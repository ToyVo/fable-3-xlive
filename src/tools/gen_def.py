"""Generate unified xlive.def from the two reference DLLs' export tables.

Usage (from repo root):
    uv run --with pefile python src/tools/gen_def.py [timeslip.dll] [disabler.dll]

Reference DLLs are NOT shipped (see docs/PROVENANCE.md); pass paths to local
copies, or place them at reference/timeslip-xlive.dll and
reference/xliveless-xlive.dll. Regenerating is optional — src/xlive.def is
committed and builds do not need it.

Output: src/xlive.def — every xLiveLess named export at its true
ordinal (verified: all Timeslip f<N> ordinals coincide with these, so one
table serves both import styles). The .def aliases everything not in IMPL
to StubSuccess.
"""
import pathlib
import sys

import pefile

ROOT = pathlib.Path(__file__).resolve().parents[2]
P_TIMESLIP = pathlib.Path(
    sys.argv[1] if len(sys.argv) > 1 else ROOT / "reference" / "timeslip-xlive.dll"
)
P_DISABLER = pathlib.Path(
    sys.argv[2] if len(sys.argv) > 2 else ROOT / "reference" / "xliveless-xlive.dll"
)
OUT = pathlib.Path(__file__).resolve().parent.parent / "xlive.def"

# Exports with hand-written C implementations (symbol name must match).
IMPL = {
    "XLiveInitialize", "XLiveInitializeEx", "XLiveUninitialize",
    "XLiveSignin", "XLiveSignout",
    "XUserGetName", "XUserGetXUID", "XUserGetSigninState",
    "XUserGetSigninInfo", "XUserCheckPrivilege",
    "XUserReadProfileSettings", "XUserWriteProfileSettings",
    "XContentCreateEnumerator", "XContentCreatePackage",
    "XLiveContentGetPath", "XEnumerate",
    "XWSAStartup", "XWSACleanup",
    "XCreateSocket", "XSocketClose", "XSocketShutdown",
    "XSocketIOCTLSocket", "XSocketSetSockOpt", "XSocketGetSockOpt",
    "XSocketHTONL", "XSocketHTONS", "XSocketNTOHL", "XSocketNTOHS",
    "XNetStartup", "XNetCleanup", "XOnlineStartup", "XOnlineCleanup",
    "XStorageEnumerate", "XStorageUploadFromMemory",
    "XStorageDownloadToMemory", "XStorageDelete",
    "XLiveSecureLoadLibraryW", "XLiveSecureFreeLibrary",
}

for label, p in (("timeslip", P_TIMESLIP), ("disabler", P_DISABLER)):
    if not p.is_file():
        sys.exit(
            f"missing {label} reference DLL: {p}\n"
            "reference DLLs are not shipped; pass paths explicitly, see --help"
        )


def exports(path):
    pe = pefile.PE(str(path))
    out = {}
    for e in pe.DIRECTORY_ENTRY_EXPORT.symbols:
        name = e.name.decode() if e.name else None
        out[e.ordinal] = name
    return out

dis = exports(P_DISABLER)
ts = exports(P_TIMESLIP)

ts_only = sorted(o for o in ts if o not in dis)
print(f"disabler: {len(dis)} exports; timeslip: {len(ts)}; timeslip-only: {ts_only}")

lines = [
    "; Unified xlive.dll — GENERATED by tools/gen_def.py, do not hand-edit.",
    "; Sources: gfwl-disabler/xlive.dll (names+ordinals, ground truth),", 
    ";          fable3-xlive-zip/xlive.dll (cross-checked: no unique ordinals).",
    "LIBRARY xlive",
    "EXPORTS",
]
for ordinal in sorted(dis):
    name = dis[ordinal]
    if name in IMPL:
        lines.append(f"{name} @{ordinal}")
    else:
        lines.append(f"{name}=StubSuccess @{ordinal}")
for ordinal in ts_only:
    # Timeslip-only ordinals keep their f<N> names as success stubs.
    lines.append(f"{ts[ordinal]}=StubSuccess @{ordinal}")

OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT} ({len(lines)-5} exports)")
